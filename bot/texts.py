def order_card(
    order_id: str,
    title: str,
    qty: int,
    amount: int,
    ttl_minutes: int,
    expires_at: datetime,
    promo: str | None = None,
) -> str:
    promo_line = f"Промокод: <b>{promo}</b>\n" if promo else ""
    return (
        f"🧾 <b>Оплата заказа</b> · <code>{order_id}</code>\n\n"
        f"Товар: <b>{title}</b>\n\n"
        f"Кол-во: {qty} шт\n"
        f"{promo_line}"
        f"Сумма к оплате: <b>{amount}₽</b>\n\n"
        f"Время на оплату: <b>{ttl_minutes} минут</b>\n"
        f"Оплатить до {expires_at.strftime('%d.%m.%Y %H:%M')} (МСК)"
    )


